// warna_variabel.cpp - menyimpan data satu warna
#include <iostream>
#include <string>

int main() {
    int merah = 255;
    int hijau = 165;
    int biru  = 0;
    std::string nama = "Oranye";
    double kecerahan = 0.65;

    std::cout << "Nama warna : " << nama << "\n";
    std::cout << "Merah      : " << merah << "\n";
    std::cout << "Hijau      : " << hijau << "\n";
    std::cout << "Biru       : " << biru << "\n";
    std::cout << "Kecerahan  : " << kecerahan << "\n";
    return 0;
}
